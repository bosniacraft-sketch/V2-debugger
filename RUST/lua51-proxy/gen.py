"""Regenerates src/generated.rs from exports.list (the exports of the game's original lua51.dll).

Run from this folder:  python gen.py
Every export that is not in HOOKED becomes a naked function that jumps to the real function
in lua5.1.dll through the REAL pointer table filled at DLL load.
"""
from pathlib import Path

HOOKED = {"luaL_openlibs", "luaL_loadbuffer", "lua_getfield", "lua_pcall"}

here = Path(__file__).resolve().parent
names = [l.strip() for l in (here / "exports.list").read_text().splitlines() if l.strip()]
assert len(names) == len(set(names)), "duplicate export name"

out = [
    "// GENERATED by gen.py from exports.list. Do not edit by hand.",
    "// Plain exports are a single jump to the real function in lua5.1.dll.",
    "",
    f"pub const COUNT: usize = {len(names)};",
    "",
    "pub static NAMES: [&[u8]; COUNT] = [",
]
out += [f'    b"{n}\\0",' for n in names]
out += ["];", ""]
out += [f"pub const IDX_{n}: usize = {i};" for i, n in enumerate(names)]
out.append("")
for i, n in enumerate(names):
    if n in HOOKED:
        continue
    out += [
        "#[unsafe(no_mangle)]",
        "#[unsafe(naked)]",
        f"pub unsafe extern \"C\" fn {n}() {{",
        f'    core::arch::naked_asm!("jmp dword ptr [{{t}} + {{o}}]", t = sym crate::REAL, o = const {i * 4});',
        "}",
        "",
    ]
(here / "src" / "generated.rs").write_text("\n".join(out), newline="\n")
print(f"generated {len(names) - len(HOOKED)} jump exports + {len(HOOKED)} hooks")
