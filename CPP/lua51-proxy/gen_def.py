"""Regenerates the export lists from exports.list (the exports of the game's original lua51.dll).

Run from this folder:  python gen_def.py
Every export that is not in HOOKED is forwarded by the Windows loader straight to the same
function in lua5.1.dll. HOOKED ones are ours (proxy.cpp). Two outputs, one per toolchain:
  lua51.def          for MinGW (GNU ld needs the forwarder quoted because of the dot in "lua5.1")
  src/forwards.h     for Visual Studio, as /export linker directives
"""
from pathlib import Path

HOOKED = {"luaL_openlibs", "luaL_loadbuffer", "lua_getfield", "lua_pcall"}

here = Path(__file__).resolve().parent
names = [l.strip() for l in (here / "exports.list").read_text().splitlines() if l.strip()]
assert len(names) == len(set(names)), "duplicate export name"
assert HOOKED <= set(names), "a hooked name is missing from exports.list"

forwarded = [n for n in names if n not in HOOKED]

out = ["; GENERATED by gen_def.py from exports.list. Do not edit by hand.", "LIBRARY lua51", "EXPORTS"]
out += [f"    {n}" for n in sorted(HOOKED)]
out += [f'    {n} = "lua5.1.{n}"' for n in forwarded]
(here / "lua51.def").write_text("\n".join(out) + "\n", newline="\n")

out = ["// GENERATED by gen_def.py from exports.list. Do not edit by hand.",
       "// Visual Studio: forwards every plain export to the same function in lua5.1.dll.",
       "#pragma once", "#ifdef _MSC_VER"]
out += [f'#pragma comment(linker, "/export:{n}=lua5.1.{n}")' for n in forwarded]
out.append("#endif")
(here / "src" / "forwards.h").write_text("\n".join(out) + "\n", newline="\n")
print(f"{len(names) - len(HOOKED)} forwarded exports + {len(HOOKED)} hooks")
